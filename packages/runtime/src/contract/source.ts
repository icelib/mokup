import type { OpenApiOperation } from './openapi'
import { generateOpenApiFixtures, importOpenApi } from './openapi'
import { schemaToTypeScript } from './typed'

function identifier(operation: OpenApiOperation) {
  const identity = `${operation.method} ${operation.path}`
  let hash = 2166136261
  for (let index = 0; index < identity.length; index++) {
    hash = Math.imul(hash ^ identity.charCodeAt(index), 16777619)
  }
  const name = (operation.operationId ?? identity).replace(/\W/giu, '_')
  return `Operation_${name}_${(hash >>> 0).toString(16)}`
}

function responseType(operation: OpenApiOperation) {
  const variants = Object.entries(operation.responses).flatMap(([status, content]) => {
    const statusType = /^\d{3}$/u.test(status) ? String(Number(status)) : 'number'
    if (Object.keys(content).length === 0 || ['204', '205', '304'].includes(status)) {
      return [`{ status: ${statusType}; body?: never; headers?: HeadersInit }`]
    }
    return Object.entries(content)
      .filter(([mime]) => mime === 'application/json' || mime.endsWith('+json') || mime.endsWith('/*'))
      .map(([, schema]) => `{ status: ${statusType}; body: ${schemaToTypeScript(schema)}; headers?: HeadersInit }`)
  })
  return variants.length ? variants.join(' | ') : 'never'
}

/** Generate a standalone TS module: structural types, validated fixtures and handler factories. */
export function generateContractSource(document: unknown): string {
  const operations = importOpenApi(document)
  const fixtures = generateOpenApiFixtures(document)
  const ids = operations.map(identifier)
  const lines = [
    '// Generated by Mokup. Runtime validation enforces constraints that TypeScript cannot express.',
    '// Unsupported or recursive schema shapes conservatively become unknown.',
    'import type { ContractResolver, OpenApiOperation } from \'mokup/contract\'',
    'import { createContractHandler } from \'mokup/contract\'',
    'import type { HttpHandler } from \'mokup/http\'',
    '',
  ]
  for (const [index, operation] of operations.entries()) {
    const request = operation.requestBody === undefined ? 'unknown' : schemaToTypeScript(operation.requestBody)
    lines.push(`export type ${ids[index]}Request = (${request})${operation.requestRequired ? '' : ' | undefined'}`)
    lines.push(`export type ${ids[index]}Response = ${responseType(operation)}`, '')
  }
  const keys = operations.map(operation => `${operation.method} ${operation.path}`)
  lines.push('export interface ContractResolvers {')
  for (const [index, key] of keys.entries()) {
    lines.push(`  ${JSON.stringify(key)}: ContractResolver<${ids[index]}Request, ${ids[index]}Response>`)
  }
  lines.push('}', '')
  // Parsing a string preserves JSON keys such as __proto__ as own properties.
  lines.push(`export const operations: OpenApiOperation[] = JSON.parse(${JSON.stringify(JSON.stringify(operations))})`, '')
  lines.push('export const fixtures: Array<{ method: string; path: string; status: number; headers: Record<string, string>; body: unknown; requestBody?: unknown }> =')
  lines.push(`  JSON.parse(${JSON.stringify(JSON.stringify(fixtures))})`, '')
  lines.push('export function createHandlers(resolvers: ContractResolvers): HttpHandler[] {', '  return [')
  for (const [index, key] of keys.entries()) {
    lines.push(`    createContractHandler<${ids[index]}Request, ${ids[index]}Response>(operations[${index}]!, resolvers[${JSON.stringify(key)}]),`)
  }
  lines.push('  ]', '}', '')
  return lines.join('\n')
}
