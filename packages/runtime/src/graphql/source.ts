import type { GraphQLSchema } from 'graphql'
import { buildSchema, getNamedType, GraphQLBoolean, GraphQLFloat, GraphQLID, GraphQLInt, GraphQLString, isEnumType, isInputObjectType, isListType, isNonNullType, isObjectType, isScalarType, printSchema } from 'graphql'

function typeName(value: string): string {
  return value.replace(/[^\w$]/gu, '_') || 'Anonymous'
}

function scalarType(value: unknown): string {
  if (value === GraphQLString || value === GraphQLID) {
    return 'string'
  }
  if (value === GraphQLInt || value === GraphQLFloat) {
    return 'number'
  }
  if (value === GraphQLBoolean) {
    return 'boolean'
  }
  return 'unknown'
}

function generatedType(value: import('graphql').GraphQLType, seen: Set<string>): string {
  if (isNonNullType(value)) {
    return generatedType(value.ofType, seen)
  }
  if (isListType(value)) {
    return `Array<${generatedType(value.ofType, seen)}> | null`
  }
  const named = getNamedType(value)
  if (isScalarType(named)) {
    return `${scalarType(named)} | null`
  }
  if (isEnumType(named)) {
    return `${typeName(named.name)} | null`
  }
  return `${typeName(named.name)} | null`
}

function generatedFieldType(value: import('graphql').GraphQLType, seen: Set<string>): string {
  const nullable = !isNonNullType(value)
  const inner = isNonNullType(value) ? value.ofType : value
  let result: string
  if (isListType(inner)) {
    result = `Array<${generatedType(inner.ofType, seen)}>`
  }
  else {
    const named = getNamedType(inner)
    result = isScalarType(named) ? scalarType(named) : isEnumType(named) ? typeName(named.name) : typeName(named.name)
  }
  return nullable ? `${result} | null` : result
}

function generatedObjectTypes(schema: GraphQLSchema): string[] {
  const lines: string[] = []
  const emitted = new Set<string>()
  const emit = (named: import('graphql').GraphQLNamedType) => {
    if (emitted.has(named.name)) {
      return
    }
    emitted.add(named.name)
    if (isEnumType(named)) {
      lines.push(`export type ${typeName(named.name)} = ${named.getValues().map(value => JSON.stringify(value.name)).join(' | ') || 'never'}`, '')
      return
    }
    if (isInputObjectType(named)) {
      lines.push(`export interface ${typeName(named.name)} {`)
      for (const field of Object.values(named.getFields())) {
        const optional = !isNonNullType(field.type)
        lines.push(`  ${field.name}${optional ? '?' : ''}: ${generatedFieldType(field.type, emitted)}`)
        const nested = getNamedType(field.type)
        if (isInputObjectType(nested)) {
          emit(nested)
        }
      }
      lines.push('}', '')
      return
    }
    if (!isObjectType(named)) {
      return
    }
    lines.push(`export interface ${typeName(named.name)} {`)
    for (const field of Object.values(named.getFields())) {
      const optional = !isNonNullType(field.type)
      lines.push(`  ${field.name}${optional ? '?' : ''}: ${generatedFieldType(field.type, emitted)}`)
      const nested = getNamedType(field.type)
      if (isObjectType(nested) || isEnumType(nested) || isInputObjectType(nested)) {
        emit(nested)
      }
      for (const argument of field.args) {
        const argumentType = getNamedType(argument.type)
        if (isInputObjectType(argumentType)) {
          emit(argumentType)
        }
      }
    }
    lines.push('}', '')
  }
  for (const named of Object.values(schema.getTypeMap())) {
    if (named.name.startsWith('__')) {
      continue
    }
    if (isObjectType(named) || isEnumType(named) || isInputObjectType(named)) {
      emit(named)
    }
  }
  return lines
}

/**
 * Generate a typed GraphQL handler module from a schema. The generated module
 * embeds the normalized SDL and routes field resolvers through the same HTTP
 * lifecycle as hand-written handlers.
 */
export function generateGraphQLSource(schemaInput: string | GraphQLSchema, options: { endpoint?: string, operations?: Readonly<Record<string, string>> } = {}): string {
  const schema = typeof schemaInput === 'string' ? buildSchema(schemaInput) : schemaInput
  const lines = [
    '// Generated by Mokup. GraphQL validation and execution remain runtime-owned.',
    `import { createGraphQLHandler, createGraphQLPersistedOperations } from 'mokup/graphql'`,
    `import type { GraphQLFieldResolver } from 'mokup/graphql'`,
    '',
    `export const schema = ${JSON.stringify(printSchema(schema))}`,
    `export const endpoint = ${JSON.stringify(options.endpoint ?? '/graphql')}`,
    `export const persistedQueries = ${JSON.stringify(options.operations ?? {})}`,
    '',
  ]
  lines.push(...generatedObjectTypes(schema))
  const rootFields: Array<{ kind: 'query' | 'mutation', name: string, args: string, result: string }> = []
  for (const [kind, root] of [
    ['query', schema.getQueryType()],
    ['mutation', schema.getMutationType()],
  ] as const) {
    if (!root) {
      continue
    }
    for (const field of Object.values(root.getFields())) {
      const operation = `${kind[0]!.toUpperCase()}${kind.slice(1)}_${typeName(field.name)}`
      lines.push(`export interface ${operation}Args {`)
      for (const argument of field.args) {
        const optional = !isNonNullType(argument.type)
        lines.push(`  ${argument.name}${optional ? '?' : ''}: ${generatedFieldType(argument.type, new Set())}`)
      }
      lines.push('}', '')
      const result = generatedFieldType(field.type, new Set()).replace(/ \| null$/u, '')
      rootFields.push({ kind, name: field.name, args: `${operation}Args`, result })
    }
  }
  lines.push('export interface GraphQLResolvers {')
  for (const field of rootFields) {
    lines.push(`  ${JSON.stringify(`${field.kind}.${field.name}`)}?: (args: ${field.args}, context: Parameters<GraphQLFieldResolver>[1]) => ${field.result} | Promise<${field.result}>`)
  }
  lines.push('}', '')
  lines.push('export function createHandlers(resolvers: GraphQLResolvers) {', '  return [createGraphQLHandler({', '    schema,', '    endpoint,', '    resolvers: resolvers as Record<string, GraphQLFieldResolver>,', '  })]', '}', '')
  lines.push('export async function createPersistedHandlers(resolvers: GraphQLResolvers) {', '  const persisted = await createGraphQLPersistedOperations(persistedQueries)', '  return [createGraphQLHandler({', '    schema,', '    endpoint,', '    persisted,', '    resolvers: resolvers as Record<string, GraphQLFieldResolver>,', '  })]', '}', '')
  return lines.join('\n')
}
